import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root=process.argv[2]||'asbplayer';
const read=name=>readFileSync(root+'/'+name,'utf8');
const resolver=read('extension/src/services/remote-dictionary.ts');
const handler=read('extension/src/handlers/video/http-post-handler.ts');
const smart=read('common/components/SmartDefinitionPanel.tsx');
const multi=read('common/components/MultiVocabularyPanel.tsx');
const ui=read('extension/src/ui/components/AnkiUi.tsx');
const bridge=read('extension/src/ui/bridge-fetcher.ts');
const config=read('extension/wxt.config.ts');
assert(resolver.includes('wiktionary(term)')&&resolver.includes('datamuse(term,sentence)'));
assert(resolver.includes('freeDictionary(term)'),'Need 3rd no-key fallback provider');
assert(resolver.includes("md:'dpr'")&&resolver.includes("ipa:'1'"));
assert(resolver.includes("response.status===404"));
assert(handler.includes('resolveRemoteDictionary(term'));
assert(handler.includes("typeof sentence === 'string' ? sentence : ''"));
assert(ui.includes('async (service, term, sentence)'));
assert(bridge.includes("body?.action === 'fluencyLookup' ? 14000"));
assert(config.includes('https://en.wiktionary.org/*'));
assert(config.includes('https://api.datamuse.com/*'));
assert(!smart.includes('const curated:') && !smart.includes('export const curated:'));
assert(!multi.includes('curated[') && !multi.includes('const known='));
assert(multi.includes('dictionaryLookup(term,controller.signal,fluencyLookup,sentence)'));
console.log('OK: all definitions online-only, context forwarded, three dictionary providers, remote IPA and no local glossary.');
