import assert from 'node:assert/strict';
import {existsSync, readFileSync} from 'node:fs';
const root=process.argv[2]||'asbplayer';
const read = path=>readFileSync(root+'/'+path,'utf8');
const multi=read('common/components/MultiVocabularyPanel.tsx');
const single=read('common/components/SmartDefinitionPanel.tsx');
const bridge=read('extension/src/handlers/video/http-post-handler.ts');
const resolver=read('extension/src/services/remote-dictionary.ts');
const ui=read('extension/src/ui/components/AnkiUi.tsx');
const transport=read('common/components/FluencyLookupTransport.ts');
assert(!existsSync(root+'/common/components/FluencyPhraseMatcher.ts'),'No preset word matcher permitted');
assert(!existsSync(root+'/extension/src/services/gemini-dictionary.ts'),'No AI dictionary permitted');
assert(!single.includes('curated[') && !multi.includes('curated['));
assert(!multi.includes('detectExpressions(') && !single.includes('detectExpression('));
assert(!multi.includes('suggestTerms(') && !single.includes('suggestTerms('));
assert(multi.includes('onChange={e=>changeWord(index,e.target.value)}'));
assert(multi.includes('dictionaryLookup(term,controller.signal,fluencyLookup)'));
assert(single.includes("dictionaryLookup(key, signal, fluencyLookup)"));
assert(multi.includes('translationLookup(term,controller.signal,fluencyLookup)'));
assert(single.includes('translationLookup(key, signal, fluencyLookup)'));
assert(single.includes("if (!term.trim() || term.length > 160) return {};"));
assert(bridge.includes("!term.trim() || term.length > 160"));
assert(bridge.includes("message.body?.action === 'fluencyLookup'"));
assert(!resolver.includes('chooseMeaning('),'No contextual sense re-ranking');
assert(!resolver.includes('sentence:string'),'Do not send subtitle to remote services');
assert(resolver.includes('wiktionary(term)')&&resolver.includes('datamuse(term)'));
assert(resolver.includes('freeDictionary(term)'));
assert(ui.includes("action: 'fluencyLookup', service, term,"));
assert(!ui.includes("sentence: sentence || ''"));
assert(transport.includes('viaBridge(service, term)'));
console.log('OK: unrestricted vocabulary search, no hardcoded words, no AI, no subtitle context, online English & Portuguese lookups.');
